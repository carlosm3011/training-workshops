#!/bin/sh
# Runs before named on every boot (dnslab-master-setup.service). On the
# first boot of an environment it generates the master's DNS setup for
# DNSLAB_GROUPS groups (set by `just init` with `docker run -e`):
#   /etc/bind/dnslab-webapp.key   TSIG key the web page uses to publish DS (#10)
#   /etc/bind/named.conf.lab      ACL, resolver and authoritative views
#   /var/lib/bind/db.lab          lab. zone delegating groupNN.lab. to each group
# Later boots leave all three alone: lab. is a dynamic zone, so named owns
# it from then on, and published DS records must survive restarts.
# Changing the number of groups means a new environment.
set -eu

eval "$(tr '\0' '\n' < /proc/1/environ | grep -E '^DNSLAB_[A-Z0-9_]+=[0-9A-Fa-f.:/]*$' | sed 's/^/export /')"

mkdir -p /var/lib/bind/keys /etc/dnslab
chown bind:bind /var/lib/bind/keys
# Filled in by dnslab-lab-anchor once named has signed lab.; it must exist
# before named starts because the resolver view includes it.
[ -e /etc/dnslab/lab-anchor.conf ] || echo '// written by dnslab-lab-anchor' > /etc/dnslab/lab-anchor.conf

[ -e /etc/bind/named.conf.lab ] && exit 0

: "${DNSLAB_GROUPS:?DNSLAB_GROUPS not set}"
echo "dnslab-master-setup: generating lab. for $DNSLAB_GROUPS groups"

tsig-keygen -a hmac-sha256 dnslab-webapp > /etc/bind/dnslab-webapp.key
chown root:bind /etc/bind/dnslab-webapp.key
chmod 640 /etc/bind/dnslab-webapp.key

zone=/var/lib/bind/db.lab
{
    cat <<'EOF'
; lab.: the lab-only parent zone, generated by dnslab-master-setup.
; Each group's zone is delegated to its three nodes; the delegations stay
; lame until students configure them. Short TTLs so DS changes show quickly.
$TTL 60
@               SOA     ns.lab. hostmaster.lab. 1 300 60 86400 60
@               NS      ns.lab.
ns              A       10.53.0.1
ns              AAAA    fd53::1
EOF
    for g in $(seq 1 "$DNSLAB_GROUPS"); do
        name=$(printf 'group%02d' "$g")
        printf '\n'
        for n in 0 1 2; do printf '%-15s NS      ns%d.%s\n' "$name" "$n" "$name"; done
        for n in 0 1 2; do
            printf '%-15s A       10.53.%d.%d\n' "ns$n.$name" "$g" $((10 + n))
            printf '%-15s AAAA    fd53::%d:%d\n' "ns$n.$name" "$g" $((10 + n))
        done
    done
} > "$zone"
chown bind:bind "$zone"
named-checkzone -q lab "$zone"

grants=$(for g in $(seq 1 "$DNSLAB_GROUPS"); do
    printf '\t\t\tgrant dnslab-webapp name group%02d.lab. DS;\n' "$g"
done)

cat > /etc/bind/named.conf.lab <<EOF
// Generated by dnslab-master-setup on the environment's first boot.
//
// One address (10.53.0.1) plays two roles, split by view:
// - recursive queries (RD=1) from the lab go to "resolver", a validating
//   resolver that finds lab. through a static-stub pointing back at this
//   server and trusts it via the anchor in /etc/dnslab/lab-anchor.conf;
// - everything else, including the resolver's own non-recursive queries
//   and anything from outside the lab, goes to "authoritative", which
//   serves the signed lab. zone and never recurses.

acl lab { 10.53.0.0/16; fd53::/64; localhost; };

include "/etc/bind/dnslab-webapp.key";

view "resolver" {
	match-clients { lab; };
	match-recursive-only yes;
	recursion yes;
	allow-recursion { lab; };
	// Never answer lab. names from the real root's cached NSEC proof
	// that lab. doesn't exist; always ask the static-stub.
	synth-from-dnssec no;

	include "/etc/dnslab/lab-anchor.conf";

	zone "lab" {
		type static-stub;
		server-addresses { 10.53.0.1; };
	};

	include "/etc/bind/named.conf.default-zones";
};

view "authoritative" {
	match-clients { any; };
	recursion no;

	zone "lab" {
		type primary;
		file "$zone";
		dnssec-policy default;
		inline-signing no;
		// Only the web page's key may change lab., and only the DS
		// records of each group's own zone (#10).
		update-policy {
$grants
		};
	};
};
EOF
chown root:bind /etc/bind/named.conf.lab
named-checkconf /etc/bind/named.conf
